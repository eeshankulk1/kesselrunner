#!/usr/bin/env node
// codex-bridge: projects the kesselrunner setup into ~/.codex so Codex behaves
// identically to Claude Code. kesselrunner stays the single source of truth; this
// script is idempotent, merge-safe (never clobbers non-generated Codex config),
// and runs as a SessionStart hook on BOTH harnesses, so any change to the setup
// propagates on the next session no matter which harness is in use.
//
// What it manages:
//   ~/.codex/AGENTS.md          <- generated from CLAUDE.md (+ harness preamble)
//   ~/.codex/skills/<name>      <- symlinks into ~/.claude/skills (shared SKILL.md standard)
//   ~/.codex/agents/<name>.toml <- generated from ~/.claude/agents/*.md
//   ~/.codex/hooks.json         <- projection of settings.json "hooks" (same schema)
//   ~/.codex/config.toml        <- surgical edits only: features.hooks, CLAUDE.md
//                                  fallback, Playwright MCP. Backed up once first.
//
// Prints one line per change; silent when everything is already in sync.
import {
  existsSync, readFileSync, writeFileSync, mkdirSync, readdirSync,
  lstatSync, readlinkSync, symlinkSync, unlinkSync, copyFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { escapeTomlBasic, parseAgent } from "../../lib/agents.mjs";

const CLAUDE_DIR = process.env.KESSELRUNNER_DIR || process.env.DOTCLAUDE_DIR || join(homedir(), ".claude");
const CODEX_DIR = process.env.CODEX_HOME || join(homedir(), ".codex");
const MARKER = "GENERATED by kesselrunner codex-bridge";
// The marker before the rename: a file that carries it is ours too, and is regenerated.
const LEGACY_MARKER = "GENERATED by dotclaude codex-bridge";
const ours = (text) => typeof text === "string" && (text.includes(MARKER) || text.includes(LEGACY_MARKER));
const changes = [];

function readIf(path) {
  try { return readFileSync(path, "utf8"); } catch { return null; }
}
// `existing` (when the caller already read the file) avoids a second read.
function writeIfChanged(path, content, label, existing) {
  if ((existing === undefined ? readIf(path) : existing) === content) return;
  writeFileSync(path, content);
  changes.push(label);
}

// ---------------------------------------------------------------- AGENTS.md
function generateAgentsMd() {
  const source = readIf(join(CLAUDE_DIR, "CLAUDE.md"));
  if (!source) return;
  const dest = join(CODEX_DIR, "AGENTS.md");
  const existing = readIf(dest);
  if (existing !== null && !ours(existing)) {
    changes.push(`SKIPPED AGENTS.md: existing file was not generated by codex-bridge (edit CLAUDE.md instead, then delete ${dest} to regenerate)`);
    return;
  }
  const preamble = `<!-- ${MARKER} from ~/.claude/CLAUDE.md. Do not edit this file;
     edit CLAUDE.md in the kesselrunner repo - this is regenerated at session start. -->

# Harness note (Codex)

The instructions below were written for Claude Code and apply to Codex unchanged, with this mapping:

- Slash commands (/pr-create, /note, /recap, ...) are skills in ~/.codex/skills/ - invoke via the skill of the same name.
- Named agents (code-reviewer, test-runner, test-updater, docs-updater, frontend-tester, ios-driver, deploy-watcher, code-scout, web-researcher, prod-reader, browser-operator) are custom subagents in ~/.codex/agents/*.toml - where the instructions say "run the X agent", spawn that subagent.
- The "claude-code-guide agent" and "Claude Code's native auto-memory" are Claude-only; ignore those references. For questions about THIS harness's behavior (hooks, config, skills), consult the Codex docs at https://developers.openai.com/codex instead of assuming.
- Paths under ~/.claude/ are valid regardless of harness: ~/.claude/kesselrunner links to the kesselrunner core, so the docs and scripts referenced below exist as written.
- The "Delegation" section is Claude-side routing: in Codex, named agents are always spawned as the subagent of that name.

`;
  writeIfChanged(dest, preamble + source, "wrote AGENTS.md from CLAUDE.md", existing);
}

// ------------------------------------------------------------------- skills
function linkSkills() {
  const srcRoot = join(CLAUDE_DIR, "skills");
  const destRoot = join(CODEX_DIR, "skills");
  if (!existsSync(srcRoot)) return;
  mkdirSync(destRoot, { recursive: true });

  const wanted = readdirSync(srcRoot).filter((name) =>
    existsSync(join(srcRoot, name, "SKILL.md")));

  for (const name of wanted) {
    const target = join(srcRoot, name);
    const link = join(destRoot, name);
    const stat = lstatOrNull(link);
    if (stat) {
      if (!stat.isSymbolicLink()) {
        changes.push(`SKIPPED skill "${name}": a non-symlink entry already exists in ~/.codex/skills`);
        continue;
      }
      if (readlinkSync(link) === target) continue;
      unlinkSync(link);
    }
    symlinkSync(target, link);
    changes.push(`linked skill ${name}`);
  }

  // Remove our now-dangling symlinks (skill deleted from kesselrunner).
  for (const name of readdirSync(destRoot)) {
    const link = join(destRoot, name);
    if (isSymlink(link) && readlinkSync(link).startsWith(srcRoot) && !existsSync(link)) {
      unlinkSync(link);
      changes.push(`unlinked removed skill ${name}`);
    }
  }
}
function lstatOrNull(path) {
  try { return lstatSync(path); } catch { return null; }
}
function isSymlink(path) {
  return lstatOrNull(path)?.isSymbolicLink() ?? false;
}

// ------------------------------------------------------------------- agents

function generateAgents() {
  const srcRoot = join(CLAUDE_DIR, "agents");
  const destRoot = join(CODEX_DIR, "agents");
  if (!existsSync(srcRoot)) return;
  mkdirSync(destRoot, { recursive: true });

  const generated = new Set();
  for (const file of readdirSync(srcRoot).filter((f) => f.endsWith(".md"))) {
    const raw = readFileSync(join(srcRoot, file), "utf8");
    const agent = parseAgent(raw);
    const name = agent?.get("name");
    if (!name) continue;
    // Guard against path traversal / escaping destRoot via a malformed name.
    if (name.includes("/") || name.includes("\\")) {
      changes.push(`SKIPPED agent from ${file}: unsafe name "${name}"`);
      continue;
    }
    const description = agent.get("description") || "";

    const toml = `# ${MARKER} from ~/.claude/agents/${file} - do not edit; edit the source.
name = "${escapeTomlBasic(name)}"
description = "${escapeTomlBasic(description)}"
developer_instructions = """
${escapeTomlBasic(agent.body.trim())}
"""
`;
    generated.add(`${name}.toml`);
    writeIfChanged(join(destRoot, `${name}.toml`), toml, `wrote agent ${name}.toml`);
  }

  // Remove generated agent files whose kesselrunner source is gone.
  for (const file of readdirSync(destRoot).filter((f) => f.endsWith(".toml"))) {
    if (generated.has(file)) continue;
    const content = readIf(join(destRoot, file));
    if (ours(content)) {
      unlinkSync(join(destRoot, file));
      changes.push(`removed stale agent ${file}`);
    }
  }
}

// ---------------------------------------------------------------- hooks.json
function generateHooksJson() {
  const settings = JSON.parse(readIf(join(CLAUDE_DIR, "settings.json")) || "{}");
  if (!settings.hooks) return;
  const dest = join(CODEX_DIR, "hooks.json");
  const existing = readIf(dest);
  if (existing !== null && !ours(JSON.parse(existing).description)) {
    changes.push(`SKIPPED hooks.json: existing file was not generated by codex-bridge`);
    return;
  }
  // Codex hooks.json uses the same schema as Claude settings.json "hooks";
  // project it verbatim. The codex-bridge SessionStart entry is already part
  // of settings.json, so both harnesses run identical hooks.
  const content = JSON.stringify(
    { description: `${MARKER} from ~/.claude/settings.json - do not edit; edit settings.json.`, hooks: settings.hooks },
    null, 2) + "\n";
  writeIfChanged(dest, content, "wrote hooks.json from settings.json hooks", existing);
}

// ---------------------------------------------------------------- config.toml
// Surgical, line-based edits: TOML forbids redefining tables, so we insert
// into existing tables rather than appending duplicates. Backed up once.
function patchConfigToml() {
  const path = join(CODEX_DIR, "config.toml");
  let content = readIf(path);
  if (content === null) content = "";
  const original = content;
  const lines = content.split("\n");
  const firstTableIdx = lines.findIndex((l) => l.trim().startsWith("["));

  // 1. Top-level: let repos without AGENTS.md fall back to their CLAUDE.md.
  if (!/^\s*project_doc_fallback_filenames\s*=/m.test(content)) {
    const insert = [`# codex-bridge: repos keep using their CLAUDE.md`, `project_doc_fallback_filenames = ["CLAUDE.md"]`, ``];
    lines.splice(firstTableIdx === -1 ? lines.length : firstTableIdx, 0, ...insert);
    changes.push("config.toml: added project_doc_fallback_filenames");
  }

  // 2. [features] hooks = true (insert into the existing table if present).
  const featuresIdx = lines.findIndex((l) => l.trim() === "[features]");
  if (featuresIdx !== -1) {
    let end = lines.findIndex((l, i) => i > featuresIdx && l.trim().startsWith("["));
    if (end === -1) end = lines.length;
    const table = lines.slice(featuresIdx, end).join("\n");
    if (!/^\s*hooks\s*=/m.test(table)) {
      lines.splice(featuresIdx + 1, 0, "hooks = true # codex-bridge");
      changes.push("config.toml: enabled hooks feature");
    }
  } else {
    lines.push("", "[features]", "hooks = true # codex-bridge");
    changes.push("config.toml: enabled hooks feature");
  }
  let updated = lines.join("\n");

  // 3. Playwright MCP (frontend-tester hard dependency).
  if (!/^\s*\[mcp_servers\.playwright\]/m.test(updated)) {
    updated += `
# codex-bridge: Playwright MCP - required by the frontend-tester agent
[mcp_servers.playwright]
command = "npx"
args = ["-y", "@playwright/mcp@latest"]
`;
    changes.push("config.toml: added Playwright MCP server");
  }

  if (updated !== original) {
    const backup = `${path}.bak-codex-bridge`;
    if (original && !existsSync(backup)) copyFileSync(path, backup);
    writeFileSync(path, updated);
  }
}

// Each stage is isolated: a failure in one (e.g. corrupt hooks.json) must
// never block the others from running, and must never block the session.
function runStage(name, fn) {
  try {
    fn();
  } catch (err) {
    changes.push(`FAILED ${name}: ${err?.message || err}`);
  }
}

try {
  mkdirSync(CODEX_DIR, { recursive: true });
  runStage("AGENTS.md", generateAgentsMd);
  runStage("skills", linkSkills);
  runStage("agents", generateAgents);
  runStage("hooks.json", generateHooksJson);
  runStage("config.toml", patchConfigToml);
  if (changes.length) process.stdout.write(`[codex-bridge] ${changes.join("; ")}\n`);
} catch (err) {
  // Best-effort: never block a session over bridge generation.
  process.stderr.write(`[codex-bridge] ${err?.message || err}\n`);
}
process.exit(0);
